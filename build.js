#!/usr/bin/env node
/*
 * Builds the three files the website publishes from the pieces in src/:
 *   index.html     <- src/head.html + src/header.html + src/sections/*.html + src/footer.html
 *   css/site.css   <- src/css/*.css   (joined in the order listed below)
 *   js/site.js     <- src/js/*.js     (joined in the order listed below, inside one wrapper)
 *
 * Edit the pieces in src/, then run:  node build.js
 * Never edit index.html, css/site.css or js/site.js by hand: the next build overwrites them.
 * Order matters. CSS rules later in the list override earlier ones, so keep the order as is.
 */
const fs = require('fs');
const path = require('path');

const root = __dirname;
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const write = (file, text) => fs.writeFileSync(path.join(root, file), text);

// Page sections, top to bottom. Change this order to reorder the page.
const sections = ['hero', 'courses', 'method', 'about', 'founder', 'schools', 'summer', 'join-faq', 'contact'];

const css = [
  '01-base', '02-header', '03-ui', '04-hero', '05-trust', '06-courses', '07-method', '08-about',
  '09-schools', '10-summer', '11-faq', '12-contact', '13-footer', '14-logo-motion',
  '15-responsive', '16-motion', '17-founder',
];

const js = [
  '01-core', '02-courses-sheet', '03-summer-gallery', '04-learning-path', '05-reveal',
  '06-nav-highlight', '07-hero-collage', '08-founder', '09-enquiry-form',
];

const banner = (open, close) => `${open} Generated by build.js from src/. Edit the files in src/, then run: node build.js ${close}\n`;
const withBanner = process.argv.includes('--plain') ? () => '' : banner;

// index.html
let html = read('src/head.html') + read('src/header.html');
html += '<main id="main">\n\n';
html += sections.map((name) => read(`src/sections/${name}.html`)).join('');
html += '</main>\n\n';
html += read('src/footer.html');
html += '<script src="js/site.js"></script>\n</body>\n</html>\n';
if (!process.argv.includes('--plain')) html = html.replace(/^<!doctype html>\n/i, (m) => m + banner('<!--', '-->'));
write('index.html', html);

// css/site.css
write('css/site.css', withBanner('/*', '*/') + css.map((name) => read(`src/css/${name}.css`)).join(''));

// js/site.js (every piece shares one scope, as before)
write('js/site.js', withBanner('/*', '*/') + '(function(){\n' + js.map((name) => read(`src/js/${name}.js`)).join('') + '})();\n');

console.log('Built index.html, css/site.css, js/site.js');
